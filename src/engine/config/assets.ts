import type { RiskLevel, Sector } from '../types';

export type AssetKind = 'stock' | 'crypto';

export interface AssetDef {
  id: string;
  ticker: string;
  name: string;
  kind: AssetKind;
  sector: Sector;
  description: string;
  risk: RiskLevel;
  /** Preço inicial em centavos. */
  basePrice: number;
  /** Tendência de longo prazo: log-retorno médio por passo de mercado. */
  drift: number;
  /** Volatilidade: desvio-padrão do log-retorno por passo. */
  volatility: number;
  /** Dividendos: fração do preço paga a cada período de dividendos. */
  dividendYield: number;
  /** Força com que o preço volta ao valor fundamental (0–1). */
  meanReversion: number;
  /** Patrimônio líquido (centavos) para o ativo aparecer. */
  unlockNetWorth: number;
}

